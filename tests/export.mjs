import {chromium} from 'playwright';
import fs from 'node:fs';
import assert from 'node:assert/strict';

const browser=await chromium.launch({headless:true,args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const url='http://127.0.0.1:8765';
try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  await page.goto(url);
  await page.waitForSelector('.three-scene canvas',{timeout:240000});
  await page.waitForFunction(()=>!document.querySelector('.loading-overlay'));
  await page.evaluate(()=>window.vio.renderAt(40));
  await page.getByRole('button',{name:'添加镜头关键帧',exact:true}).click();
  const first=await page.evaluate(()=>window.vio.getCamera());
  await page.evaluate(()=>window.vio.renderAt(48));
  await page.getByRole('button',{name:'俯视',exact:true}).click();
  await page.evaluate(()=>window.vio.renderAt(48));
  await page.getByRole('button',{name:'添加镜头关键帧',exact:true}).click();
  const last=await page.evaluate(()=>window.vio.getCamera());
  await page.getByRole('button',{name:'关键帧镜头',exact:true}).click();
  await page.evaluate(()=>window.vio.renderAt(47.99));
  const nearEnd=await page.evaluate(()=>window.vio.getCamera());
  assert(Math.abs(nearEnd.quaternion.reduce((s,x,i)=>s+x*last.quaternion[i],0))>.9999);
  await page.screenshot({path:'test-results/keyframe-end.png'});
  await page.evaluate(()=>window.vio.renderAt(44));
  const middle=await page.evaluate(()=>window.vio.getCamera());
  for(let i=0;i<3;i++)assert(Math.abs(middle.position[i]-(first.position[i]+last.position[i])/2)<1e-7);
  await page.getByRole('checkbox',{name:'显示 RANSAC',exact:true}).uncheck();
  assert.equal(await page.locator('.scene-legend').getByText('RANSAC',{exact:true}).count(),0);
  await page.getByRole('checkbox',{name:'显示 RANSAC',exact:true}).check();
  await page.getByRole('button',{name:'导出',exact:true}).click();
  await page.getByLabel('导出起点',{exact:true}).fill('40');
  await page.getByLabel('导出终点',{exact:true}).fill('42');
  await page.getByLabel('导出帧率',{exact:true}).selectOption('24');
  await page.getByRole('button',{name:'关闭',exact:true}).click();
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'保存工程',exact:true}).click();
  await (await download).saveAs('test-results/demo.vio.json');
  const project=JSON.parse(fs.readFileSync('test-results/demo.vio.json','utf8'));
  assert.equal(project.view.keyframes.length,2);assert.deepEqual(project.clip,[40,42]);
  await page.reload();
  await page.waitForFunction(()=>!document.querySelector('.loading-overlay')&&document.querySelector('canvas'));
  await page.getByLabel('选择序列',{exact:true}).selectOption(project.id);
  await page.waitForFunction(()=>window.vio.getState().settings.keyframes.length===2);
  await page.getByRole('button',{name:'导出',exact:true}).click();
  await page.getByLabel('导出分辨率',{exact:true}).selectOption('720');
  await page.getByLabel('导出帧率',{exact:true}).selectOption('24');
  const snapshotRequest=page.waitForResponse(r=>r.url()===url+'/api/export'&&r.request().method()==='POST');
  await page.getByRole('button',{name:'当前帧 PNG',exact:true}).click();
  const snapshot=await (await snapshotRequest).json();
  await page.getByRole('link',{name:'下载截图',exact:true}).waitFor({timeout:120000});
  const videoRequest=page.waitForResponse(r=>r.url()===url+'/api/export'&&r.request().method()==='POST');
  await page.getByRole('button',{name:'导出 MP4',exact:true}).click();
  const video=await (await videoRequest).json();
  console.log(JSON.stringify({snapshot:snapshot.output,video:video.output,job:video.id}));
  await page.getByRole('link',{name:'下载视频',exact:true}).waitFor({timeout:600000});
  const result=await (await page.request.get(url+'/api/export/'+video.id)).json();
  assert.equal(result.status,'done');assert.equal(result.frame,48);
  assert(fs.statSync(video.output).size>10000);
  fs.copyFileSync(video.output,'test-results/export-video.mp4');
  fs.copyFileSync(snapshot.output,'test-results/export-snapshot.png');
  fs.writeFileSync('test-results/export.json',JSON.stringify(result,null,2));
  console.log(JSON.stringify({status:'passed',frames:result.frame,cameraInterpolation:true,saveReload:true}));
}finally{await browser.close();}
