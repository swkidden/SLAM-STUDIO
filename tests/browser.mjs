import {chromium} from 'playwright';
import fs from 'node:fs';
import assert from 'node:assert/strict';
fs.mkdirSync('test-results',{recursive:true});
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
try{
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8765');
 await page.waitForSelector('.three-scene canvas',{timeout:240000});
 await page.waitForFunction(()=>!document.querySelector('.loading-overlay'));
 assert.equal(await page.title(),'SLAM Studio');
 assert.equal(await page.getByRole('checkbox',{name:'显示 VINS-Fusion (historical)',exact:true}).count(),1);
 assert.equal(await page.locator('.scene-tags,.scene-readout,.film-caption,.eyebrow,.version').count(),0);
 await page.evaluate(()=>window.vio.renderAt(40));
 await page.waitForFunction(()=>!document.querySelector('.frame-loading'));
 await page.screenshot({path:'test-results/desktop.png'});
 const canvas=await page.evaluate(()=>{
   const c=document.querySelector('canvas'),gl=c.getContext('webgl2');
   const pixels=new Uint8Array(c.width*c.height*4);gl.readPixels(0,0,c.width,c.height,gl.RGBA,gl.UNSIGNED_BYTE,pixels);
   const colors=new Set();for(let i=0;i<pixels.length;i+=64)colors.add(`${pixels[i]},${pixels[i+1]},${pixels[i+2]}`);
   return {width:c.width,height:c.height,colors:colors.size};
 });
 assert(canvas.colors>20,JSON.stringify(canvas));
 const old=await page.locator('.camera-frame img').first().getAttribute('src');
 await page.getByRole('button',{name:'下一帧',exact:true}).click();
 await page.waitForTimeout(300);
 assert.notEqual(await page.locator('.camera-frame img').first().getAttribute('src'),old);
 await page.getByRole('button',{name:'播放',exact:true}).click();
 await page.waitForTimeout(1800);
 const progressed=await page.evaluate(()=>window.vio.getState().time);assert(progressed>40.1);
 await page.getByRole('button',{name:'暂停',exact:true}).click();
 await page.getByRole('button',{name:'俯视',exact:true}).click();
 const topCamera=await page.evaluate(()=>window.vio.getCamera());
 await page.screenshot({path:'test-results/top.png'});
 await page.getByRole('button',{name:'论文白色 / 展示深色'}).click();
 await page.screenshot({path:'test-results/light.png'});
 await page.getByRole('button',{name:'论文白色 / 展示深色'}).click();
 await page.getByRole('button',{name:'自由视角',exact:true}).click();
 assert.notDeepEqual(await page.evaluate(()=>window.vio.getCamera()),topCamera);
 await page.setViewportSize({width:390,height:844});
 await page.waitForTimeout(300);
 await page.screenshot({path:'test-results/mobile.png'});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
 assert.equal(overflow,false);
 const mobileColors=await page.evaluate(()=>{
   const c=document.querySelector('canvas'),gl=c.getContext('webgl2'),pixels=new Uint8Array(c.width*c.height*4);
   gl.readPixels(0,0,c.width,c.height,gl.RGBA,gl.UNSIGNED_BYTE,pixels);
   const colors=new Set();for(let i=0;i<pixels.length;i+=64)colors.add(pixels.slice(i,i+3).join(','));
   return colors.size;
 });
 assert(mobileColors>20);
 await page.evaluate(()=>window.vio.renderAt(45));
 await page.waitForFunction(()=>!document.querySelector('.frame-loading'));
 await page.setViewportSize({width:1920,height:1080});
 await page.getByRole('button',{name:'展示模式',exact:true}).click();
 await page.screenshot({path:'test-results/presentation.png'});
 await page.getByRole('button',{name:'退出展示',exact:true}).click();
 const previousSession=await page.evaluate(()=>window.vio.getState().session);
 await page.getByLabel('选择序列',{exact:true}).selectOption('city_day_3_high');
 await page.waitForFunction(old=>window.vio.getState().session!==old&&!document.querySelector('.loading-overlay'),previousSession,{timeout:240000});
 await page.evaluate(()=>window.vio.renderAt(35));
 await page.waitForFunction(()=>!document.querySelector('.frame-loading'));
 assert.equal(await page.getByRole('checkbox',{name:'显示 VINS-Fusion',exact:true}).count(),0);
 await page.screenshot({path:'test-results/city-day.png'});
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({canvas,mobileColors,progressed,overflow,errors,session:await page.evaluate(()=>window.vio.getState().session)}));
}finally{await browser.close();}
